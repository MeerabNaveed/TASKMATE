from pptx import Presentation
from pptx.util import Pt
from datetime import datetime

def generate_ppt(title, slides_data):
    files = {}
    try:
        prs = Presentation()
        slide = prs.slides.add_slide(prs.slide_layouts[0])
        slide.shapes.title.text = title
        slide.placeholders[1].text = "Generated by TaskMate AI"
        
        for s in slides_data:
            slide = prs.slides.add_slide(prs.slide_layouts[1])
            slide.shapes.title.text = s.get("title", "Slide")
            lines = s.get("content", "").strip().split("\n")
            bullets = "".join(f"• {l.strip()}\n" for l in lines if l.strip())
            slide.placeholders[1].text = bullets
            
        fname = f"{title.replace(' ', '_')}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pptx"
        prs.save(fname)
        files["pptx"] = fname
    except Exception as e:
        files["pptx"] = None
        files["error"] = str(e)
    return files
def generate_html(title, slides_data):
    try:
        fname = f"{title.replace(' ', '_')}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.html"
        slides_html = ""
        for s in slides_data:
            content = "".join(f"<li>{line}</li>" for line in s.get('content', '').split('\n') if line.strip())
            slides_html += f"""
            <div style="height: 100vh; display: flex; justify-content: center; align-items: center; background: #14142b; color: white; padding: 50px;">
                <div style="background: rgba(255,255,255,0.1); padding: 40px; border-radius: 20px; max-width: 800px; width: 100%;">
                    <h1 style="color: #6C63FF;">{s.get('title', 'Slide')}</h1>
                    <ul style="font-size: 1.2rem; line-height: 1.8;">{content}</ul>
                </div>
            </div>
            """
        
        full_html = f"<!DOCTYPE html><html><head><title>{title}</title><style>body{{margin:0;font-family:sans-serif;scroll-snap-type:y mandatory;overflow-y:scroll;}} div{{scroll-snap-align:start;}}</style></head><body>{slides_html}</body></html>"
        
        with open(fname, "w", encoding="utf-8") as f:
            f.write(full_html)
        return fname
    except Exception:
        return None